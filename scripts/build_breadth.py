def quotas(rows: list[dict], n: int, cap_frac: float) -> dict:
    """Rows per (source, stream) for an n-row set (float), by the recipe of the module docstring."""
    kept = [r for r in rows if r["kept"] == "yes"]
    cap = cap_frac * n
    used = collections.Counter()
    out: dict = {}
    carry = 0.0
    for st, share in STREAMS.items():
        target = share * n + carry
        supply = {r["source"]: r[f"ok_{st}"] for r in kept if r[f"ok_{st}"] > 0}
        lim = {s: min(v, max(cap - used[s], 0)) for s, v in supply.items()}
        bid = {r["source"]: ("B12" if st == "LV" else r["br_id"]) for r in kept}
        cap_b = collections.Counter()
        for s, v in lim.items():
            cap_b[bid[s]] += v
        brow = waterfill(target, {b: B_ROWS[b] for b in cap_b}, dict(cap_b)) if st != "LV" else \
            {"B12": min(target, cap_b["B12"])}
        got = 0.0
        score = {r["source"]: float(r["ts_score"] or 0) for r in kept}
        for b, tot in brow.items():
            members = {s: score[s] * math.sqrt(supply[s]) for s in lim if bid[s] == b}
            if st == "S" and any(s.startswith("oasst2") for s in members):
                group = [s for s in members if s.startswith("oasst2")]
                gl = min(sum(lim[s] for s in group), STREAMS["S"] * n / 3)
                ent = {s: w for s, w in members.items() if s not in group}
                ent["oasst2*"] = sum(members[s] for s in group)
                el = {s: lim[s] for s in ent if s != "oasst2*"}
                el["oasst2*"] = gl
                q = waterfill(tot, ent, el)
                gq = q.pop("oasst2*", 0.0)
                q.update(waterfill(gq, {s: members[s] for s in group}, {s: lim[s] for s in group}))
            else:
                q = waterfill(tot, members, lim)
            for s, v in q.items():
                out[(s, st)] = v
                used[s] += v
                got += v
        carry = max(target - got, 0.0)
    return out


def nested_int_quotas(rows: list[dict], sizes: list[int], cap_frac: float) -> dict:
    """Integer quotas per size, made monotone in the size (so the smaller set is a subset of the larger)."""
    kept = {r["source"]: r for r in rows if r["kept"] == "yes"}
    res = {}
    prev = None
    for n in sorted(sizes, reverse=True):
        q = quotas(rows, n, cap_frac)
        lim = {k: kept[k[0]][f"ok_{k[1]}"] for k in q}
        if prev is not None:
            lim = {k: min(v, prev.get(k, 0)) for k, v in lim.items()}
            q = {k: min(v, lim[k]) for k, v in q.items()}
            deficit = n - sum(q.values())
            if deficit > 0:          # clipping to the larger set's quotas: spread the rest where there is room
                extra = waterfill(deficit, {k: v for k, v in q.items() if v > 0},
                                  {k: lim[k] - q[k] for k in q})
                q = {k: v + extra.get(k, 0.0) for k, v in q.items()}
        res[n] = round_exact(q, n, lim)
        prev = res[n]
    return res


def collect(keep_k: dict, seed: int, max_chars: int) -> dict:
    """The keep_k[(source, stream)] smallest-hash renderable rows of each stratum, rendered."""
    import pyarrow.parquet as pq
    heaps: dict = collections.defaultdict(list)
    cols = ["state", "kind", "id", "options", "target", "question", "source", "variant", "license_use"]
    want = {s for s, _ in keep_k}
    for f in sorted(glob.glob(str(POOL / "data/train-*.parquet"))):
        t = pq.read_table(f, columns=cols).to_pydict()
        for i, s in enumerate(t["source"]):
            if s not in want:
                continue
            k, v = t["kind"][i], t["variant"][i]
            key = (s, stream_of(k, v))
            kk = keep_k.get(key, 0)
            if not kk or not renderable(k, t["options"][i], t["target"][i], t["state"][i], t["question"][i],
                                        max_chars):
                continue
            h = rowhash(seed, s, t["id"][i])
            hp = heaps[key]
            if len(hp) < kk:
                heapq.heappush(hp, (-h, {c: t[c][i] for c in cols}))
            elif -hp[0][0] > h:
                heapq.heapreplace(hp, (-h, {c: t[c][i] for c in cols}))
        del t
    out = {}
    for key, hp in heaps.items():
        rows = []
        for negh, row in sorted(hp, key=lambda x: -x[0]):
            rec = render(row, random.Random(f"{seed}-{row['source']}-{row['id']}"))
            if rec is None or len(rec["prompt"]) > max_chars:
                continue
            s = row["source"]
            target = list(row["target"])
            soft = any(0.0 < x < 1.0 for x in target)
            rec.update({"item_id": f"ts-{hashlib.md5((s + str(row['id'])).encode()).hexdigest()[:12]}",
                        "source": f"tasksource/{s}", "family": s, "variant": row["variant"],
                        "license_use": row["license_use"], "label_basis": "vote_share" if soft else "gold",
                        "node_basis": "none", "subqs": [], "random_subqs": [], "_h": -negh, "_stream": key[1]})
            rows.append(rec)
        out[key] = rows
    return out


