def licence_class(lic: str, use: str) -> str:
    """The most restrictive class of a sources.yaml / row licence string, with per_source.csv's conventions."""
    lo = lic.lower()
    if use == "non-commercial" or any(k in lo for k in ("-nc", "nc-", "non commercial", "non-commercial", "openai",
                                                        "request form", "academic", "research")):
        return "NC"
    if any(k in lo for k in ("sa-", "-sa", "share", "gpl", "oanc", "odbl", "mpl")):
        return "SA"
    if use != "commercial":
        return "UNK"
    if any(k in lo for k in ("cc-by", "cc by", "odc-by", "c-uda")):
        return "ATTR"
    if any(k in lo for k in ("mit", "apache", "bsd", "afl", "cc0", "public domain")):
        return "PERM"
    return "UNK"


def rowhash(seed: int, source: str, rid: str) -> int:
    return int(hashlib.md5(f"{seed}|{source}|{rid}".encode()).hexdigest()[:15], 16)


def stream_of(kind: str, variant: str) -> str:
    return "LV" if variant == "label_verification" else {"choice": "C", "noul": "N", "score": "S"}[kind]


def renderable(kind, options, target, state, question, max_chars) -> bool:
    if len(state or "") + len(question or "") > max_chars - 300:
        return False
    if kind == "noul":
        return target is not None and len(target) == 1
    return options is not None and 2 <= len(options) <= 10 and target is not None and len(target) == len(options) \
        and sum(target) > 0


def waterfill(total: float, weights: dict, limits: dict) -> dict:
    """Split total in proportion to weights, no key above its limit; what a key cannot take goes to the others."""
    out, weights = {}, {k: w for k, w in weights.items() if w > 0 and limits.get(k, 0) > 0}
    while weights and total > 1e-9:
        scale = total / sum(weights.values())
        full = {k for k, w in weights.items() if w * scale >= limits[k]}
        if not full:
            out.update({k: w * scale for k, w in weights.items()})
            break
        for k in full:
            out[k] = limits[k]
            total -= limits[k]
            del weights[k]
    return out


def round_exact(q: dict, total: int, limits: dict) -> dict:
    """Integer quotas summing to min(total, sum of limits): floors, then the largest remainders."""
    out = {k: min(int(v), limits[k]) for k, v in q.items()}
    rest = sorted(q, key=lambda k: -(q[k] - int(q[k])))
    need = total - sum(out.values())
    for k in rest * 2:
        if need <= 0:
            break
        if out[k] < limits[k]:
            out[k] += 1
            need -= 1
    return out


