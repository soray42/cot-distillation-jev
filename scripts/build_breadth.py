def scan_pool(max_chars: int) -> dict:
    import pyarrow.parquet as pq
    stats: dict = collections.defaultdict(collections.Counter)
    lic = {}
    cols = ["kind", "source", "variant", "license", "license_use", "options", "target", "state", "question"]
    for f in sorted(glob.glob(str(POOL / "data/train-*.parquet"))):
        t = pq.read_table(f, columns=cols).to_pydict()
        for k, s, v, l, u, o, tg, st, q in zip(*(t[c] for c in cols)):
            c = stats[s]
            c["rows"] += 1
            c[k] += 1
            c["label_verification"] += v == "label_verification"
            lic[s] = (l or "", u or "")
            if renderable(k, o, tg, st, q, max_chars):
                c["ok:" + stream_of(k, v)] += 1
        del t
    return {"stats": stats, "lic": lic}


