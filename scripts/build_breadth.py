def masked_words(text: str) -> list[str]:
    return ["#" if any(ch.isdigit() for ch in w) else w for w in TOK.findall(text.lower())]


def ngram_hashes(words: list[str], n: int):
    """Hashes of the n-grams with at least half real words (runs of masked numbers, e.g. tables or chess FEN, match
    anything)."""
    import numpy as np
    m = [w == "#" for w in words]
    return np.fromiter((hash(tuple(words[i:i + n])) for i in range(len(words) - n + 1)
                        if sum(m[i:i + n]) * 2 <= n), dtype=np.int64)


def body(prompt: str) -> str:
    """The problem text of a prompt: before its options and its final question line (as scripts/eval_overlap.py), so
    lettered numeric option lists, which are generic once digits are masked, are not compared."""
    b = prompt.rpartition("\nOptions:")[0] or prompt
    return b.rpartition("\n\nQuestion:")[0] or b


