class MaskedGate:
    """Plan §3.4 item 2: a candidate is flagged when it shares a digit-masked n-gram with any data/eval item (except the
    typed-decision-layout files of TD_FORMAT) or math reference (n-grams in >= boilerplate reference items ignored, as decontam.py), or when its masked word set has
    Jaccard >= jacc with a math reference (exact, prefix filtering on a rare-first token order)."""

    def __init__(self, n: int = 10, jacc: float = .5, boilerplate: int = 20):
        self.n, self.jacc = n, jacc
        self.ref_h, self.ref_o, self.names, self.msets, self.df, self.index, self.ref_counts = masked_refs(
            n, jacc, boilerplate)

    def order(self, s):
        return sorted(s, key=lambda w: (self.df.get(w, 0), w))

    def __call__(self, cands: list[dict]) -> dict:
        import numpy as np
        flagged: dict[str, str] = {}
        for r in cands:
            words = masked_words(body(r["prompt"]))
            g = ngram_hashes(words, self.n)
            if len(g):
                pos = np.searchsorted(self.ref_h, g)
                pos[pos >= len(self.ref_h)] = 0
                m = self.ref_h[pos] == g
                if m.any():
                    flagged[r["item_id"]] = f"masked{self.n}:{self.names[int(self.ref_o[pos[m][0]])]}"
                    continue
            if words.count("#") < 2:                    # every math reference states >= 2 numbers
                continue
            s = frozenset(words)
            o = self.order(s)
            seen = set()
            for w in o[:len(o) - math.ceil(self.jacc * len(o)) + 1]:
                for j in self.index.get(w, ()):
                    if j in seen:
                        continue
                    seen.add(j)
                    t = self.msets[j][1]
                    if self.jacc * len(s) <= len(t) <= len(s) / self.jacc and \
                            len(s & t) >= self.jacc * len(s | t):
                        flagged[r["item_id"]] = f"jaccard:{self.msets[j][0]}"
                        break
                if r["item_id"] in flagged:
                    break
        return flagged


def masked_refs(n: int, jacc: float, boilerplate: int):
    import numpy as np
    texts: list[tuple[str, str]] = []
    for path in sorted(glob.glob(str(ROOT / "data/eval/*.jsonl"))):
        name = Path(path).stem
        if TD_FORMAT.match(name):      # rendered in our own State/Question/Options layout: the 13-gram gate covers them
            continue
        for line in open(path):
            if line.strip():
                texts.append((name, body(json.loads(line).get("prompt", ""))))
    mrefs = math_references()
    for name, qs in mrefs.items():
        texts += [(name, q) for q in qs]
    names = sorted({t[0] for t in texts})
    nid = {x: i for i, x in enumerate(names)}
    hs, owners = [], []
    for name, t in texts:
        g = np.unique(ngram_hashes(masked_words(t), n))
        hs.append(g)
        owners.append(np.full(len(g), nid[name], dtype=np.int32))
    allh = np.concatenate(hs)
    allo = np.concatenate(owners)
    del hs, owners
    uniq, first, counts = np.unique(allh, return_index=True, return_counts=True)
    keep = counts < boilerplate
    ref_h, ref_o = uniq[keep], allo[first[keep]]
    del allh, allo, uniq, first, counts
    msets = []
    for name in mrefs:
        msets += [(name, frozenset(masked_words(q))) for q in mrefs[name]]
    for path in sorted(glob.glob(str(ROOT / "data/eval/*.jsonl"))):      # math evals once they are built
        if MATH_HINT.search(Path(path).stem):
            msets += [(Path(path).stem, frozenset(masked_words(body(json.loads(l)["prompt"])))) for l in open(path)
                      if l.strip()]
    df = collections.Counter(w for _, s in msets for w in s)
    index = collections.defaultdict(list)
    for j, (_, s) in enumerate(msets):
        o = sorted(s, key=lambda w: (df.get(w, 0), w))
        for w in o[:len(o) - math.ceil(jacc * len(o)) + 1]:
            index[w].append(j)
    counts = {k: len(v) for k, v in mrefs.items()}
    counts.update(collections.Counter(nm for nm, _ in msets if nm not in mrefs))
    return ref_h, ref_o, names, msets, df, index, counts


